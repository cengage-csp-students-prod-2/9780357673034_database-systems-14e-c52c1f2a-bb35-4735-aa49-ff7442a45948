SELECT I.CUS_CODE,
I.INV_NUMBER,
P.P_DESCRIPT,
L.LINE_UNITS
AS "Units Bought", L.LINE_PRICE
AS "Unit Price", ROUND(L.LINE_UNITS * L.LINE_PRICE, 2) AS "Subtotal"
FROM CUSTOMER C, INVOICE I, LINE L, PRODUCT P
WHERE
C.CUS_CODE = I.CUS_CODE
AND
I.INV_NUMBER = L.INV_NUMBER
AND
P.P_CODE = L.P_CODE
ORDER BY
I.CUS_CODE, I.INV_NUMBER, P.P_DESCRIPT;