SELECT
CUSTOMER.CUS_CODE,
INVOICE.INV_NUMBER,
INVOICE.INV_DATE,
PRODUCT.P_DESCRIPT,
LINE.LINE_UNITS,
LINE.LINE_PRICE
FROM CUSTOMER
JOIN INVOICE ON
CUSTOMER.CUS_CODE=INVOICE.CUS_CODE
JOIN LINE ON
INVOICE.INV_NUMBER=LINE.INV_NUMBER
JOIN PRODUCT ON
LINE.P_CODE=PRODUCT.P_CODE
ORDER BY CUS_CODE, INV_NUMBER, P_DESCRIPT;