SELECT
COUNT(DISTINCT INVOICE.INV_NUMBER) as 'Total Invoices',
ROUND(SUM(LINE.LINE_UNITS * LINE.LINE_PRICE), 2) as 'Total Sales',
(SELECT ROUND(MIN(total), 2)
FROM (SELECT SUM(LINE.LINE_UNITS * LINE.LINE_PRICE) as total
FROM INVOICE
JOIN LINE ON INVOICE.INV_NUMBER = LINE.INV_NUMBER
GROUP BY INVOICE.CUS_CODE) as min_purchase) as 'Minimum Customer Purchases',
(SELECT ROUND(MAX(total), 2)
FROM (SELECT SUM(LINE.LINE_UNITS * LINE.LINE_PRICE) as total
FROM INVOICE
JOIN LINE ON INVOICE.INV_NUMBER = LINE.INV_NUMBER
GROUP BY INVOICE.CUS_CODE) as max_purchase) as 'Largest Customer Purchases',
ROUND((SELECT AVG(total)
FROM (SELECT SUM(LINE.LINE_UNITS * LINE.LINE_PRICE) as total
FROM INVOICE
JOIN LINE ON INVOICE.INV_NUMBER = LINE.INV_NUMBER
GROUP BY INVOICE.CUS_CODE) as avg_purchase), 2) as 'Average Customer Purchases'
FROM INVOICE
JOIN LINE ON INVOICE.INV_NUMBER = LINE.INV_NUMBER;