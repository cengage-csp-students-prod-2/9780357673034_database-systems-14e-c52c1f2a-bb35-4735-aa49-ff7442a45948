SELECT
P.PAT_ID,
P.PAT_LNAME,
COUNT(C.CHECK_NUM) AS "NUM CHECKOUTS",
COUNT(DISTINCT C.BOOK_NUM) AS "NUM DIFFERENT BOOKS"
FROM
PATRON P
JOIN
CHECKOUT C ON P.PAT_ID = C.PAT_ID
GROUP BY
P.PAT_ID, P.PAT_LNAME
HAVING
COUNT(C.CHECK_NUM) >= 3
ORDER BY
COUNT(DISTINCT C.BOOK_NUM) DESC,
COUNT(C.CHECK_NUM) DESC,
P.PAT_ID ASC;