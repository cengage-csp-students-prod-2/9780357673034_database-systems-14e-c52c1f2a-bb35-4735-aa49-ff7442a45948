SELECT
AUTHOR.AU_ID,
AUTHOR.AU_LNAME,
BOOK.BOOK_TITLE,
CHECKOUT.CHECK_OUT_DATE,
PATRON.PAT_LNAME
FROM
AUTHOR
JOIN
WRITES ON AUTHOR.AU_ID = WRITES.AU_ID
JOIN
BOOK ON WRITES.BOOK_NUM = BOOK.BOOK_NUM
JOIN
CHECKOUT ON BOOK.BOOK_NUM = CHECKOUT.BOOK_NUM
JOIN
PATRON ON CHECKOUT.PAT_ID = PATRON.PAT_ID
WHERE
AUTHOR.AU_LNAME = "Bruer" AND PATRON.PAT_LNAME = "Miles"
ORDER BY
CHECKOUT.CHECK_OUT_DATE;