SELECT
B.BOOK_NUM,
B.BOOK_TITLE,
B.BOOK_SUBJECT,
A.AU_LNAME,
COUNT(W2.BOOK_NUM) AS "Num Books by Author"
FROM
BOOK B
JOIN
WRITES W ON B.BOOK_NUM = W.BOOK_NUM
JOIN
AUTHOR A ON W.AU_ID = A.AU_ID
JOIN
WRITES W2 ON A.AU_ID = W2.AU_ID
WHERE
B.BOOK_SUBJECT = 'Cloud'
GROUP BY
B.BOOK_NUM,
B.BOOK_TITLE,
B.BOOK_SUBJECT,
A.AU_LNAME
ORDER BY
B.BOOK_TITLE,
A.AU_LNAME;